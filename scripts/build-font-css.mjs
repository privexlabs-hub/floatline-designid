/**
 * Generates src/styles/fonts.css from the committed font manifest.
 * Hand-editing that file will fail `verify-fonts`, which is the point.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const m = JSON.parse(await readFile(path.join(ROOT, 'public/brand/fonts/fonts.manifest.json'), 'utf8'));

const head = `/* ============================================================
   GENERATED by scripts/build-font-css.mjs — do not hand-edit.
   Source: ${m.generatedFrom.join('\n            ')}
   Licence: ${m.licence}

   Self-hosted on purpose. html-to-image's getFontEmbedCSS reads
   document.styleSheets[].cssRules; a cross-origin Google sheet throws
   SecurityError there and the faces vanish SILENTLY — every export would
   ship in fallback type with nothing to indicate it.
   ============================================================ */

`;

const faces = m.fonts
  .map((f) =>
    [
      '@font-face {',
      `  font-family: '${f.family}';`,
      `  font-style: ${f.style};`,
      `  font-weight: ${f.weight};`,
      '  font-display: block;',
      `  src: url('/brand/fonts/${f.file}') format('woff2');`,
      f.unicodeRange ? `  unicode-range: ${f.unicodeRange};` : null,
      '}',
    ]
      .filter(Boolean)
      .join('\n')
  )
  .join('\n\n');

const tail = `

/* Bricolage carries an optical-size axis; without this the display sizes do not
   tighten and the wordmark sits wrong against the mark. */
:root {
  font-optical-sizing: auto;
}
`;

await writeFile(path.join(ROOT, 'src/styles/fonts.css'), head + faces + tail);
console.log(`[build-font-css] wrote ${m.fonts.length} @font-face rules`);
